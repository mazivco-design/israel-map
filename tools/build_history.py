def clip(g):
    g = g.intersection(LAND).intersection(VIEW)
    return g.simplify(0.002).buffer(0)


def main():
    out = []
    for p in PERIODS:
        feats = []
        for i, a in enumerate(p["areas"]):
            g = clip(a["g"])
            if g.is_empty:
                print("empty area:", p["id"], a["name"])
                continue
            lp = g.representative_point() if g.geom_type == "Polygon" else max(g.geoms, key=lambda x: x.area).representative_point()
            gm = mapping(g)

            def rnd(c):
                return [rnd(x) for x in c] if isinstance(c[0], (list, tuple)) else [round(c[0], 4), round(c[1], 4)]
            gm = {"type": gm["type"], "coordinates": rnd(gm["coordinates"])}
            feats.append({"type": "Feature", "properties": {"name": a["name"], "color": a["color"], "approx": a["approx"], "lx": round(lp.x, 4), "ly": round(lp.y, 4), "i": i},
                          "geometry": gm})
        sites = []
        for n, t in p["sites"]:
            if n not in SITES:
                raise SystemExit(f"missing site {n}")
            sites.append({"n": n, "t": t, "c": list(SITES[n])})
        e = {k: p[k] for k in ("id", "from", "to", "name", "short", "ruler", "text")}
        e["areas"] = {"type": "FeatureCollection", "features": feats}
        e["sites"] = sites
        if p.get("line"):
            e["line"] = {"type": "Feature", "properties": {"name": p["lineName"]}, "geometry": {"type": "LineString", "coordinates": [list(c) for c in p["line"]]}}
        out.append(e)
    json.dump({"periods": out,
               "credit": "גבולות החשמונאים והורדוס: Ancient World Mapping Center (ODbL). שאר הגבולות משוערים, לפי אטלסים היסטוריים. מיקומי אתרים: Pleiades (CC-BY)."},
              open("history.json", "w"), ensure_ascii=False, separators=(",", ":"))
    print(len(out), "periods")


if __name__ == "__main__":
    main()
